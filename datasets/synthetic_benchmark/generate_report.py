"""
SUPMS-Fair Report Generator
============================
Reads evaluation_summary.json and writes the final markdown report.
"""

import json
from pathlib import Path
from datetime import datetime

BASE_DIR  = Path(__file__).parent
EVAL_DIR  = BASE_DIR / "evaluation"
META_DIR  = BASE_DIR / "metadata"
GT_DIR    = BASE_DIR / "ground_truth"


def run():
    summary_path = EVAL_DIR / "evaluation_summary.json"
    if not summary_path.exists():
        print("ERROR: Run evaluate_anonymizer.py first.")
        return

    with open(summary_path) as f:
        s = json.load(f)

    gt_file = GT_DIR / "annotations.json"
    total_frac_overlap = 0
    if gt_file.exists():
        with open(gt_file) as f:
            all_gt = json.load(f)
        total_frac_overlap = sum(1 for a in all_gt if a.get("has_fracture_overlap"))

    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    report = f"""# SUPMS-Fair Medical Image Anonymization Benchmark Report

**Generated:** {now}

---

## Research Integrity Statement

> The FracAtlas radiographs are de-identified source images. Synthetic
> patient/radiology identifiers were programmatically introduced into **copies**
> of the radiographs to create a controlled ground-truth benchmark for
> evaluating image de-identification. All patient identifiers are entirely
> synthetic and do not correspond to real individuals. The anonymizer's
> performance reported here is based solely on the execution of this
> controlled experiment.

---

## Dataset Summary

| Metric | Value |
|---|---|
| Total images processed | {s['total_images_processed']} |
| Failed images | {s['failed_images']} |
| Total synthetic PHI fields inserted | {s['total_phi_fields_inserted']} |
| Images with fracture-overlap PHI (Group B) | {total_frac_overlap} |
| Images without fracture-overlap (Group A) | {s['total_images_processed'] - total_frac_overlap} |

---

## PHI Detection Results

### Overall (IoU threshold primary: 0.50)

| Metric | Value |
|---|---|
| True Positives (TP) | {s['total_phi_detected']} |
| False Negatives / Missed PHI (FN) | {s['total_phi_missed']} |
| False Positives (FP) | {s['total_false_positives']} |
| REVIEW-flagged (not silently passed) | {s['total_review_flagged']} |

### Precision / Recall / F1 at Multiple IoU Thresholds

| IoU Threshold | Precision | Recall | F1 |
|---|---|---|---|
| **0.50** (primary) | **{s['precision_at_50']:.4f}** | **{s['recall_at_50']:.4f}** | **{s['f1_at_50']:.4f}** |
| 0.30 | {s['precision_at_30']:.4f} | {s['recall_at_30']:.4f} | {s['f1_at_30']:.4f} |
| 0.75 | {s['precision_at_75']:.4f} | {s['recall_at_75']:.4f} | {s['f1_at_75']:.4f} |

### Additional Metrics

| Metric | Value |
|---|---|
| Redaction Recall | {s['redaction_recall']:.4f} |
| REVIEW Rate | {s['review_rate']:.4f} |
| Avg Processing Time / Image | {s['average_processing_time_s']:.2f}s |

---

## Fracture-Aware Group Analysis

| Group | Description | Recall @0.50 |
|---|---|---|
| **Group A** | PHI does NOT overlap fracture region | {s['group_A_no_overlap_recall']:.4f} |
| **Group B** | PHI overlaps fracture region | {s['group_B_frac_overlap_recall']:.4f} |

Group B tests the **fracture-aware pixelation** behavior: PHI overlapping
a fracture bounding box should be **pixelated** rather than solid-black
redacted to preserve diagnostic continuity for the radiologist.

---

## Definitions

- **TP**: Ground-truth PHI box matched to a redacted box at ≥ IoU threshold.
- **FN**: Ground-truth PHI box not matched (missed by anonymizer).
- **FP**: Redacted box not matched to any ground-truth PHI box.
- **REVIEW**: OCR line classified as ambiguous; surfaced to caller, NOT silently cleared.
- **Group A**: PHI does not intersect any YOLO fracture bounding box.
- **Group B**: At least one PHI field intersects a YOLO fracture bounding box (IoU > 0).

---

*Report generated by SUPMS-Fair evaluation pipeline.*
"""

    report_path = EVAL_DIR / "evaluation_report.md"
    report_path.write_text(report, encoding="utf-8")
    print(f"Report saved to: {report_path}")


if __name__ == "__main__":
    run()
